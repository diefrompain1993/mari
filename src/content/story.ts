export const findScene = (
  id: string,
): { scene: number; beat: number } | undefined => {
  for (let s = 0; s < story.length; s++) {
    if (story[s].id === id) return { scene: s, beat: 0 };
    const b = story[s].beats.findIndex((v) => v.id === id);
    if (b >= 0) return { scene: s, beat: b };
  }
  return undefined;
};
export const stagesAt = (scene: number, beat: number) => {
  let hero = story[scene].hero,
    girl = story[scene].girl;
  for (const b of story[scene].beats.slice(0, beat + 1)) {
    hero = b.hero ?? hero;
    girl = b.girl ?? girl;
  }
  return { hero, girl };
};
